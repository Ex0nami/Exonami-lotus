from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
folder=root/'assets/sleep'
# Encode the finished artwork for the hardware's 1-bit, MSB-first framebuffer.
portrait=Image.open(folder/'exonami-source.png').convert('L').resize((480,800),Image.Resampling.LANCZOS).point(lambda v:255 if v>=160 else 0,mode='1')
portrait.save(folder/'exonami-portrait.png')
# Rotate the previous panel image 90 degrees counterclockwise. Keep artwork
# at its original size; only blank margins are cropped to fit the panel.
rotated=portrait.transpose(Image.Transpose.ROTATE_270).transpose(Image.Transpose.ROTATE_90)
assert rotated.crop((0,0,480,160)).getextrema()==(255,255)
assert rotated.crop((0,640,480,800)).getextrema()==(255,255)
panel=Image.new('1',(800,480),1)
panel.paste(rotated.crop((0,160,480,640)),(160,0))
panel.save(folder/'exonami-panel.png')
packed=panel.tobytes()
assert len(packed)==48000
assert Image.frombytes('1',(800,480),packed).tobytes()==panel.tobytes()
header='// Generated by custom/encode-sleep-art.py. 800x480, MSB first, 1=white.\n#pragma once\n#include <cstdint>\nnamespace sticky_lotus::assets {\ninline constexpr std::uint8_t exonamiSleep[] = {\n'
header+='\n'.join('    '+', '.join(f'0x{v:02X}' for v in packed[i:i+20])+',' for i in range(0,len(packed),20))
header+='\n};\nstatic_assert(sizeof(exonamiSleep)==800*480/8);\n}\n'
(folder/'exonami_sleep.h').write_text(header)
print('Encoded panel rotated 90 degrees counterclockwise: 48,000 bytes. Blank-margin crop and round-trip verified.')
