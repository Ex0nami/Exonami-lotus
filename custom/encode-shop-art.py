"""Encode the shop crest and menu lion for the Sticky's one-bit display."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageOps

assets = Path(__file__).resolve().parents[1] / "assets"
source = Image.open(assets / "sleep/loewenherz-source.png").convert("L")
# The supplied artwork is light on dark. Drop the faint background grid.
mask = source.point(lambda value: 255 if value >= 130 else 0)


def encode(mask, preview, header, name, size, artwork_size):
    mask = mask.crop(mask.getbbox())
    mask.thumbnail(artwork_size, Image.Resampling.LANCZOS)
    width, height = size
    x, y = (width - mask.width) // 2, (height - mask.height) // 2
    image = Image.new("1", size, 1)
    image.paste(ImageOps.invert(mask).point(lambda value: 0 if value < 155 else 255, "1"), (x, y))
    image.save(assets / preview)

    packed = image.tobytes()
    assert width % 8 == 0 and len(packed) == width * height // 8
    rows = [
        "    " + ", ".join(f"0x{value:02X}" for value in packed[i:i + 20]) + ","
        for i in range(0, len(packed), 20)
    ]
    (assets / header).write_text("\n".join([
        "// Generated by custom/encode-shop-art.py. MSB first, 1 = white.",
        "#pragma once", "#include <cstdint>", "", "namespace sticky_lotus::assets {",
        f"inline constexpr int {name}Width = {width};",
        f"inline constexpr int {name}Height = {height};",
        f"inline constexpr std::uint8_t {name}[] = {{", *rows, "};",
        f"static_assert(sizeof({name}) == {name}Width * {name}Height / 8);",
        "}", "",
    ]), encoding="ascii")


encode(mask, "sleep/loewenherz-panel.png", "sleep/loewenherz_sleep.h",
       "shopSleep", (800, 480), (400, 408))

# Remove the shield outline, then crop away the wordmark to keep the lion and cards.
lion = mask.copy()
ImageDraw.floodfill(lion, (62, 100), 0)
lion = lion.crop((116, 180, 369, 466))
encode(lion, "icons/loewenherz-menu.png", "icons/loewenherz_menu_icon.h",
       "shopMenuIcon", (40, 42), (38, 40))
